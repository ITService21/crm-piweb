-- Quotations and invoices share one table (doc_type) because they share numbering, snapshots, line items, PDF and email.
-- Only invoices use payments. For quotations `due_date` means "valid until".
CREATE TABLE billing_documents (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  doc_type                 ENUM('invoice','quotation') NOT NULL,
  doc_number               VARCHAR(60) NOT NULL,
  lead_id                  BIGINT UNSIGNED NOT NULL,
  seq                      INT UNSIGNED NOT NULL,
  status                   VARCHAR(20) NOT NULL DEFAULT 'draft',
  issue_date               DATE NOT NULL,
  due_date                 DATE NULL,
  currency                 CHAR(3) NOT NULL DEFAULT 'INR',
  payment_terms            VARCHAR(500) NULL,
  po_number                VARCHAR(100) NULL,
  place_of_supply          VARCHAR(150) NULL,
  client_notes             TEXT NULL,
  internal_notes           TEXT NULL,
  client_name              VARCHAR(255) NULL,            -- denormalised from the snapshot for search/list
  client_snapshot          JSON NOT NULL,
  issuer_snapshot          JSON NOT NULL,
  subtotal                 DECIMAL(14,2) NOT NULL DEFAULT 0,
  discount_total           DECIMAL(14,2) NOT NULL DEFAULT 0,
  taxable_amount           DECIMAL(14,2) NOT NULL DEFAULT 0,
  tax_amount               DECIMAL(14,2) NOT NULL DEFAULT 0,
  additional_charges       DECIMAL(14,2) NOT NULL DEFAULT 0,
  additional_charges_label VARCHAR(100) NULL,
  total                    DECIMAL(14,2) NOT NULL DEFAULT 0,
  amount_paid              DECIMAL(14,2) NOT NULL DEFAULT 0,
  source_quotation_id      BIGINT UNSIGNED NULL,
  idempotency_key          VARCHAR(64) NULL,
  issued_at                DATETIME(3) NULL,
  issued_by                INT UNSIGNED NULL,
  responded_at             DATETIME(3) NULL,
  cancelled_at             DATETIME(3) NULL,
  cancelled_by             INT UNSIGNED NULL,
  cancel_reason            VARCHAR(500) NULL,
  created_by               INT UNSIGNED NULL,
  updated_by               INT UNSIGNED NULL,
  created_at               DATETIME(3) NOT NULL,
  updated_at               DATETIME(3) NOT NULL,
  UNIQUE KEY uq_doc_number (doc_number),
  UNIQUE KEY uq_doc_lead_seq (doc_type, lead_id, seq),
  UNIQUE KEY uq_doc_idem (idempotency_key),
  KEY idx_doc_lead (lead_id),
  KEY idx_doc_list (doc_type, status, issue_date),
  KEY idx_doc_created (doc_type, created_at),
  CONSTRAINT fk_doc_lead      FOREIGN KEY (lead_id)             REFERENCES leads(id),
  CONSTRAINT fk_doc_source    FOREIGN KEY (source_quotation_id) REFERENCES billing_documents(id),
  CONSTRAINT fk_doc_issued_by FOREIGN KEY (issued_by)           REFERENCES users(id),
  CONSTRAINT fk_doc_cancel_by FOREIGN KEY (cancelled_by)        REFERENCES users(id),
  CONSTRAINT fk_doc_created   FOREIGN KEY (created_by)          REFERENCES users(id),
  CONSTRAINT fk_doc_updated   FOREIGN KEY (updated_by)          REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE billing_document_items (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  document_id     BIGINT UNSIGNED NOT NULL,
  position        SMALLINT UNSIGNED NOT NULL,
  name            VARCHAR(255) NOT NULL,
  description     TEXT NULL,
  quantity        DECIMAL(12,3) NOT NULL,
  unit_price      DECIMAL(14,2) NOT NULL,
  discount_type   ENUM('none','percent','amount') NOT NULL DEFAULT 'none',
  discount_value  DECIMAL(14,3) NOT NULL DEFAULT 0,
  tax_rate        DECIMAL(7,3) NULL,
  gross_amount    DECIMAL(14,2) NOT NULL,
  discount_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
  taxable_amount  DECIMAL(14,2) NOT NULL,
  tax_amount      DECIMAL(14,2) NOT NULL DEFAULT 0,
  line_total      DECIMAL(14,2) NOT NULL,
  KEY idx_items_doc (document_id, position),
  CONSTRAINT fk_items_doc FOREIGN KEY (document_id) REFERENCES billing_documents(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE invoice_payments (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  document_id     BIGINT UNSIGNED NOT NULL,
  amount          DECIMAL(14,2) NOT NULL,
  paid_on         DATE NOT NULL,
  method          VARCHAR(40) NULL,
  reference       VARCHAR(150) NULL,
  notes           TEXT NULL,
  idempotency_key VARCHAR(64) NULL,
  created_by      INT UNSIGNED NULL,
  created_at      DATETIME(3) NOT NULL,
  UNIQUE KEY uq_pay_idem (document_id, idempotency_key),
  KEY idx_pay_doc (document_id, paid_on),
  CONSTRAINT fk_pay_doc  FOREIGN KEY (document_id) REFERENCES billing_documents(id),
  CONSTRAINT fk_pay_user FOREIGN KEY (created_by)  REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE document_emails (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  document_id BIGINT UNSIGNED NOT NULL,
  to_email    VARCHAR(190) NOT NULL,
  cc_email    VARCHAR(190) NULL,
  subject     VARCHAR(255) NOT NULL,
  status      ENUM('sent','failed') NOT NULL,
  error       VARCHAR(500) NULL,
  message_id  VARCHAR(255) NULL,
  sent_by     INT UNSIGNED NULL,
  created_at  DATETIME(3) NOT NULL,
  KEY idx_email_doc (document_id, created_at),
  CONSTRAINT fk_email_doc  FOREIGN KEY (document_id) REFERENCES billing_documents(id),
  CONSTRAINT fk_email_user FOREIGN KEY (sent_by)     REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
